use super::*;

fn read(text: &str) -> PrintInfo {
    let mut c = Collector::default();
    for line in text.lines() {
        c.line(line);
    }
    let mut scanned = Collector::default();
    scanned.scan(text);
    let info = c.finish();
    assert_eq!(scanned.finish(), info);
    info
}

#[test]
fn qidi_uses_the_selected_spool_plate_and_job_estimate() {
    let text = r#"; HEADER_BLOCK_START
; QIDIStudio 02.07.02.73
; total filament weight [g] : 8.45
; total layer number: 420
; max_z_height: 33.88
; filament: 2
; HEADER_BLOCK_END
; EXECUTABLE_BLOCK_START
M141 S50
M141 S0
; EXECUTABLE_BLOCK_END
; total filament used [g] = 0, 8.41
; estimated printing time (normal mode) = 1h 53m 36s
; CONFIG_BLOCK_START
; default_filament_profile = PLA
; filament_settings_id = PLA;"ASA; Natural"
; filament_colour = #FFFFFF;#123456
; curr_bed_type = Textured PEI Plate
; hot_plate_temp = 60,90
; textured_plate_temp = 60,70
; nozzle_temperature_initial_layer = 210,245
; nozzle_temperature = 215,250
; layer_height = 0.08
; CONFIG_BLOCK_END"#;
    let info = read(text);
    assert_eq!(info.filament.as_deref(), Some("ASA; Natural"));
    assert_eq!(info.swatch, Some([0x12, 0x34, 0x56]));
    assert_eq!(info.consumption, Some((8.45, "G")));
    assert_eq!(info.bed.later, Some(70.));
    assert_eq!(
        info.nozzle,
        Targets {
            first: Some(245.),
            later: Some(250.)
        }
    );
    assert_eq!(info.chamber, Some(50.));
    assert_eq!(
        (info.layers, info.nominal, info.top_z),
        (Some(420), Some(0.08), Some(33.88))
    );
    assert_eq!(info.time, Some(6816));
}

#[test]
fn bambu_packed_weights_do_not_identify_used_spools_by_position() {
    let text = "; BambuStudio\n; model printing time: 7m 41s; total estimated time: 15m 33s\n; filament: 1,3\n; total filament weight [g] : 2.5,1.5\n; filament_settings_id = PLA;unused;PETG\n; filament_colour = #FFFFFF;#000000;#AABBCC\n; nozzle_temperature = 210,0,250";
    let info = read(text);
    assert_eq!(info.time, Some(933));
    assert_eq!(info.consumption, Some((4., "G")));
    assert_eq!(info.filament.as_deref(), Some("2 FILAMENTS"));
    assert_eq!(info.swatch, None);
    assert_eq!(info.nozzle, Targets::default());
}

#[test]
fn prusa_uses_total_once_and_selects_the_nonempty_slot() {
    let info = read(
        "; generated by PrusaSlicer\n; filament used [mm] = 0, 8\n; total filament used [g] = 0.02\n; total filament used for wipe tower [g] = 0.01\n; filament_settings_id = ;PETG\n; filament_colour = ;#ab3456\n; first_layer_bed_temperature = 0,75\n; bed_temperature = 0,70\n; layer_height = 0.2\n; max_print_height = 250\n; estimated printing time (silent mode) = 4h",
    );
    assert_eq!(info.consumption, Some((0.02, "G")));
    assert_eq!(info.filament.as_deref(), Some("PETG"));
    assert_eq!(
        info.bed,
        Targets {
            first: Some(75.),
            later: Some(70.)
        }
    );
    assert_eq!((info.layers, info.top_z, info.time), (None, None, None));
}

#[test]
fn cura_distinguishes_length_volume_and_initial_targets() {
    let marlin = read(
        ";FLAVOR:Marlin\n;TIME:675\n;Filament used: 0.5m, 0.125m\n;Layer height: 0.3\n;MAXZ:0.275\n;LAYER_COUNT:1",
    );
    assert_eq!(marlin.consumption, Some((0.625, "M")));
    assert_eq!(
        (marlin.time, marlin.layers, marlin.nominal, marlin.top_z),
        (Some(675), Some(1), Some(0.3), None)
    );
    let griffin = ";FLAVOR:Griffin\n;PRINT.TIME:517\n;EXTRUDER_TRAIN.1.MATERIAL.VOLUME_USED:1110\n;EXTRUDER_TRAIN.1.INITIAL_TEMPERATURE:205\n;BUILD_PLATE.INITIAL_TEMPERATURE:60\n;PRINT.SIZE.MAX.Z:5";
    let info = read(griffin);
    assert_eq!(info.consumption, None);
    assert_eq!(
        info.nozzle,
        Targets {
            first: Some(205.),
            later: None
        }
    );
    assert_eq!(info.bed.first, Some(60.));
    let ambiguous = read(&format!(
        "{griffin}\n;EXTRUDER_TRAIN.0.INITIAL_TEMPERATURE:100\n;LAYER_COUNT:12\n;LAYER_COUNT:12"
    ));
    assert_eq!((ambiguous.nozzle.first, ambiguous.layers), (None, None));
    let job = format!(
        "{griffin}\n;EXTRUDER_TRAIN.0.INITIAL_TEMPERATURE:100\n;END_OF_HEADER\n;Generated with Cura_SteamEngine\nT1\nM82\nG1 X5"
    );
    assert_eq!(
        read(&job).nozzle,
        Targets {
            first: Some(205.),
            later: None
        }
    );
    assert_eq!(
        read(&job.replace("T1\nM82", "G1 X1\nT1")).nozzle.first,
        None
    );
    assert_eq!(
        read(";FLAVOR:Marlin(Volumetric)\n;Filament used: 59mm3").consumption,
        None
    );
}

#[test]
fn invalid_or_absent_data_does_not_invent_fields() {
    let text = "; generated by OrcaSlicer\n; total filament weight [g] : 10,NaN\n; total filament length [mm] : 2500\n; estimated printing time (normal mode) = 2h broken\n; curr_bed_type = Unknown\n; hot_plate_temp = 90\n; M141 S50\n; chamber_temperatures = 50\n; support_chamber_temp_control = 1\n; start_gcode = M141 S50\\n; total layer number: 888\n; THUMBNAIL_BLOCK_START\n; total layer number: 999\n; THUMBNAIL_BLOCK_END";
    assert_eq!(
        read(text),
        PrintInfo {
            consumption: Some((2.5, "M")),
            ..Default::default()
        }
    );
}
